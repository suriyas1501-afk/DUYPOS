/**
 * ผู้ใช้งานปัจจุบัน (พนักงานที่เข้าสู่ระบบ) แบบอ่านได้จากไลบรารีที่ไม่ใช่ React
 *
 * เอกสารทุกใบ (บิลขาย / ใบคืน / รับของเข้า / นับสต็อก / รายจ่าย / กะ) ต้องบันทึกว่า "ใครทำ"
 * แต่ไลบรารีเหล่านั้นเรียกจากหลายที่และอยู่ใน transaction จึงไม่สะดวกส่ง staff ลงไปทุกชั้น
 * → App.tsx เป็นผู้ setActor() ทุกครั้งที่ผู้ใช้เปลี่ยน แล้วไลบรารีอ่านผ่าน getActor()
 *
 * ถ้าการทำรายการนั้น "คนอื่นอนุมัติ" (เช่น ผู้จัดการใส่ PIN อนุมัติให้ยกเลิกบิล)
 * ให้ส่ง actor เข้าไปตรงๆ ที่ฟังก์ชันนั้น อย่าพึ่งค่านี้
 */
export interface Actor {
  id?: number
  name?: string
}

let current: Actor = {}

export const setActor = (a: Actor) => {
  current = a
}

export const getActor = (): Actor => current
